// Optional UI check: node test-editor-browser.js <path-to-playwright> <path-to-chrome>
const {chromium}=require(process.argv[2]||'playwright');
const {pathToFileURL}=require('node:url');
const path=require('node:path');
const assert=require('node:assert/strict');
(async()=>{
  const browser=await chromium.launch({headless:true,executablePath:process.argv[3],args:['--no-sandbox']});
  const page=await browser.newPage({viewport:{width:1280,height:830}});
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  await page.goto(pathToFileURL(path.join(__dirname,'index.html')).href);
  await page.evaluate(()=>localStorage.clear());
  await page.reload();
  await page.locator('#start').click();await page.keyboard.press('Enter');await page.locator('[data-stage="0"]').click();
  const before=await page.evaluate(()=>platforms.filter(p=>p.level===0).length);
  await page.locator('#editor-toggle').click();
  assert.equal(await page.evaluate(()=>state),'editor');
  await page.locator('[data-editor-tool="platform"]').click();
  await page.locator('#game').click({position:{x:455,y:320}});
  assert.equal(await page.evaluate(()=>platforms.filter(p=>p.level===0).length),before+1);
  await page.locator('#editor-goal').fill('11');await page.locator('#editor-goal').dispatchEvent('change');
  assert.equal(await page.evaluate(()=>biomes[0].goal),11);
  await page.locator('#editor-resume').click();assert.equal(await page.evaluate(()=>state),'play');
  await page.reload();
  assert.equal(await page.evaluate(()=>platforms.filter(p=>p.level===0).length),before+1,'saved platform survives reload');
  assert.equal(await page.evaluate(()=>biomes[0].goal),11,'saved goal survives reload');
  await page.locator('#start').click();await page.keyboard.press('Enter');await page.locator('[data-stage="0"]').click();
  await page.locator('#editor-toggle').click();await page.locator('#editor-reset').click();
  assert.equal(await page.evaluate(()=>platforms.filter(p=>p.level===0).length),before);
  await page.locator('#editor-undo').click();assert.equal(await page.evaluate(()=>platforms.filter(p=>p.level===0).length),before+1);
  await page.locator('#editor-flying-speed').evaluate(input=>{input.value='50';input.dispatchEvent(new Event('change',{bubbles:true}));});
  assert.equal(await page.evaluate(()=>{spawnMonster('bat',player.x+400);return enemies.at(-1).speed;}),36,'flyer speed control changes new enemies');
  assert.equal(await page.evaluate(()=>monsterStats.sandjaw.hp),300);
  await page.screenshot({path:path.join(__dirname,'previews','level-editor.png')});
  await page.keyboard.press('F2');assert.equal(await page.evaluate(()=>state),'play');await page.evaluate(()=>{unlockedStage=1;enterLevel(1);});
  await page.locator('#editor-toggle').click();assert.equal(await page.locator('#editor-boss-fields').isVisible(),true);
  await page.locator('#editor-boss-health').evaluate(input=>{input.value='60';input.dispatchEvent(new Event('change',{bubbles:true}));});
  await page.locator('#editor-boss-damage').evaluate(input=>{input.value='70';input.dispatchEvent(new Event('change',{bubbles:true}));});
  const tunedBoss=await page.evaluate(()=>{spawnMonster('sandjaw',stage*LEVEL_LENGTH+300);const boss=enemies.at(-1);return {hp:boss.hp,damage:boss.damage};});
  assert.deepEqual(tunedBoss,{hp:180,damage:8},'boss controls tune the live Sandjaw');
  assert.deepEqual(errors,[],'browser page has no JavaScript errors');
  const oldEditor=await browser.newContext({viewport:{width:1280,height:830}}),oldPage=await oldEditor.newPage();
  await oldPage.goto(pathToFileURL(path.join(__dirname,'index.html')).href);
  await oldPage.evaluate(()=>localStorage.setItem('alistairs-wildlands-editor-v1',JSON.stringify({version:1,levels:{5:{camps:[{editorId:'old-rest',x:5*4800+2550,used:false}]}}})));
  await oldPage.reload();
  assert.ok(await oldPage.evaluate(()=>camps.some(c=>c.x===5*LEVEL_LENGTH+3590)),'older editor saves gain the new pre-Warden rest stop');
  assert.ok(await oldPage.evaluate(()=>[3860,4050,4500].every(offset=>traps.some(t=>t.x===5*LEVEL_LENGTH+offset))),'older editor saves gain the new Warden traps');
  await oldPage.evaluate(()=>localStorage.setItem('alistairs-wildlands-editor-v1',JSON.stringify({version:2,levels:{5:{traps:[{editorId:'old-warden-trap',x:5*4800+4250,kind:'crystal-trap',w:56,h:25}]}}})));
  await oldPage.reload();
  assert.ok(await oldPage.evaluate(()=>[3860,4050,4250,4500].every(offset=>traps.some(t=>t.x===5*LEVEL_LENGTH+offset))),'version 2 editor saves keep the existing trap and gain the new ones');
  await oldEditor.close();
  const phone=await browser.newContext({viewport:{width:844,height:390},hasTouch:true,isMobile:true});
  const mobile=await phone.newPage();const mobileErrors=[];mobile.on('pageerror',error=>mobileErrors.push(error.message));
  await mobile.goto(pathToFileURL(path.join(__dirname,'index.html')).href);
  await mobile.locator('#start').tap();await mobile.locator('[data-control="map"]').tap();await mobile.locator('[data-stage="0"]').tap();
  const mobileBefore=await mobile.evaluate(()=>traps.filter(t=>t.x<LEVEL_LENGTH).length);
  await mobile.locator('[data-control="edit"]').tap();assert.equal(await mobile.evaluate(()=>state),'editor');
  await mobile.locator('[data-editor-tool="thorns"]').tap();await mobile.locator('#game').tap({position:{x:180,y:240}});
  assert.equal(await mobile.evaluate(()=>traps.filter(t=>t.x<LEVEL_LENGTH).length),mobileBefore+1);
  await mobile.screenshot({path:path.join(__dirname,'previews','level-editor-phone.png')});
  await mobile.locator('#editor-resume').tap();assert.equal(await mobile.evaluate(()=>state),'play');
  assert.deepEqual(mobileErrors,[],'phone page has no JavaScript errors');await phone.close();
  await browser.close();console.log('PASS: editor places objects, pauses play, saves across reload, resets and undoes.');
})().catch(error=>{console.error(error);process.exitCode=1;});
